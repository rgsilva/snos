#!/usr/bin/env python3
"""Bake the console fonts into ROM, exactly as con_init used to compute them.

con_init built both VRAM font banks at runtime: 12,288 port writes plus a
glyph_row()/rev() computation per row, re-run on every app exit (con_gfx(0)
calls con_init), which measured as roughly half a second of blank screen each
time. The bytes never change between runs, so they are computed HERE, once,
at build time, and con_init DMAs them from ROM — cartridge ROM is on the
A-bus and VRAM on the B-bus, the same observation that made image DMA fast.

The layout must match what the old loops wrote, byte for byte (VRAM words are
little-endian through $2118/$2119):

  BG2 (2bpp), char c: 8 words glyph_row(c,y), then 8 words 0  -> 32 B/char
  BG1 (4bpp), char c: 16 words 0, 8 words glyph_row(c,y), 8 words 0 -> 64 B/char

glyph_row: chars $80-$FF are the inverse-video twins of $00-$7F; slots $01-$06
carry box-drawing glyphs (public domain, Daniel Hepper's font8x8 U+2500 block,
same source as font8x8_basic.h); font8x8 is LSB-left, the SNES wants MSB-left,
hence the bit reversal. Any change to that logic in console.c must land here
too — the console renders every character through these tables, so a mismatch
is caught by the first test that reads the screen.

Usage: mkfont.py <font8x8_basic.h> <out.c>
"""
import re
import sys

BOX = [
    [0x00, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00],  # 1 horizontal
    [0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08],  # 2 vertical
    [0x00, 0x00, 0x00, 0x00, 0xF8, 0x08, 0x08, 0x08],  # 3 top-left
    [0x00, 0x00, 0x00, 0x00, 0x0F, 0x08, 0x08, 0x08],  # 4 top-right
    [0x08, 0x08, 0x08, 0x08, 0xF8, 0x00, 0x00, 0x00],  # 5 bottom-left
    [0x08, 0x08, 0x08, 0x08, 0x0F, 0x00, 0x00, 0x00],  # 6 bottom-right
]


def parse_font(path):
    src = open(path).read()
    rows = re.findall(r"\{([^{}]*)\}", src)  # innermost braces only
    font = []
    for r in rows:
        vals = [int(v, 0) for v in r.split(",") if v.strip()]
        if len(vals) == 8:
            font.append(vals)
    assert len(font) == 128, f"expected 128 glyphs, parsed {len(font)}"
    return font


def rev(b):
    b = ((b & 0xF0) >> 4) | ((b & 0x0F) << 4)
    b = ((b & 0xCC) >> 2) | ((b & 0x33) << 2)
    b = ((b & 0xAA) >> 1) | ((b & 0x55) << 1)
    return b


def glyph_row(font, ch, y):
    base = ch & 0x7F
    g = rev(BOX[base - 1][y]) if 1 <= base <= 6 else rev(font[base][y])
    if ch & 0x80:
        g = ~g & 0xFF
    return g


def words_bg2(font):
    for ch in range(256):
        for y in range(8):
            yield glyph_row(font, ch, y)
        for _ in range(8):
            yield 0


def words_bg1(font):
    for ch in range(256):
        for _ in range(16):
            yield 0
        for y in range(8):
            yield glyph_row(font, ch, y)
        for _ in range(8):
            yield 0


def emit(f, name, words):
    data = bytearray()
    for w in words:
        data += bytes((w & 0xFF, (w >> 8) & 0xFF))
    f.write(f"const uint8_t {name}[{len(data)}] = {{\n")
    for i in range(0, len(data), 16):
        f.write("  " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
    f.write("};\n\n")
    return len(data)


def main():
    font = parse_font(sys.argv[1])
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/mkfont.py -- do not edit. See that file\n"
                " * for the layout contract with kernel/console.c. */\n"
                "#include <stdint.h>\n\n")
        n2 = emit(f, "snos_font_bg2", words_bg2(font))
        n1 = emit(f, "snos_font_bg1", words_bg1(font))
    print(f"mkfont: bg2 {n2} B, bg1 {n1} B")


if __name__ == "__main__":
    main()
