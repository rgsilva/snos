#!/usr/bin/env python3
"""Combine the keyboard and gateway bridges into one loadable script.

Mesen's Script Window runs one script at a time, so loading the gateway bridge
unloads the keyboard one and vice versa. This produces a single script that
starts both.

WHY EACH HALF IS WRAPPED IN A FUNCTION rather than simply concatenated:

  - `return`. netbridge.lua returns early when I/O access is disabled. At the
    top level of a combined chunk that return would abort EVERYTHING, silently
    taking the keyboard down with it — and the symptom would be "my keyboard
    stopped working when I enabled the gateway", which points nowhere near the
    cause.

  - Locals. Both scripts declare a top-level `MB`, meaning different things
    ($7EF000 for the test mailbox, $7EE000 for the link). Concatenated, whether
    that works depends on which closures were created before the second
    declaration shadowed the first. It happens to work today. That is not a
    property to rely on.

Each half registers its own endFrame callback, which Mesen is happy to do, so
they run independently once started.
"""
import os
import sys


def wrap(name, path):
    body = open(path, encoding="utf-8-sig").read()  # a BOM is legal at the start
    return f"local function {name}()\n{body}\nend\n"  # of a file, fatal mid-file


def main(argv):
    out_path, kbd, net = argv
    parts = [
        "-- GENERATED by tools/mkbridge.py -- edit kbdbridge.lua or netbridge.lua\n",
        "--\n",
        "-- Load this ONE script in Mesen's Script Window to get both the host\n",
        "-- keyboard and the gateway link. The gateway half needs\n",
        "-- Debug -> Script Window -> 'Allow access to I/O and OS functions';\n",
        "-- without it that half reports the fact and stops, and the keyboard\n",
        "-- half carries on regardless.\n\n",
        wrap("snos_start_keyboard", kbd),
        "\n",
        wrap("snos_start_gateway", net),
        "\nsnos_start_keyboard()\nsnos_start_gateway()\n",
    ]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    open(out_path, "w").write("".join(parts))
    print(f"  bridge {out_path}")


if __name__ == "__main__":
    main(sys.argv[1:])
