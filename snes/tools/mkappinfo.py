#!/usr/bin/env python3
"""Emit the SNOS application header for one app.

The header sits at offset $0000 of the app's first ROM bank and makes the
cartridge self-describing: the kernel finds applications by walking bank starts
looking for the magic, so there is no directory to keep in sync and adding an
app is purely a build-time act.

Layout must match APPHDR_* in snes/kernel/app.h.

Usage: mkappinfo.py <name> <banks> <out.s> [min-kernel-abi] [arena-page] [arena-pages]
"""
import os
import sys

NAME_LEN = 16


def main(argv):
    name, banks, out_path = argv[0], int(argv[1]), argv[2]
    minabi = int(argv[3]) if len(argv) > 3 else 1
    # Arena slot, in 256-byte pages of bank $7F (M10 step 4): start page and
    # page count, 0 pages meaning "all 256" so the whole arena still fits a
    # byte. Lives in the two bytes the checksum never used, so the header
    # stays 32 bytes and the $20 trampoline never moves.
    arena_page = int(argv[4], 0) if len(argv) > 4 else 0
    arena_pages = int(argv[5], 0) if len(argv) > 5 else 0
    if len(name) > NAME_LEN:
        raise SystemExit(f"app name {name!r} exceeds {NAME_LEN} characters")
    padded = name.ljust(NAME_LEN, "\0")

    lines = [
        ";;; Generated by tools/mkappinfo.py — do not edit.",
        '        .rtmodel version, "1"',
        '        .rtmodel core, "*"',
        "        .section appheader, root",
        "        .extern app_start",
        '        .ascii  "SNOS"           ; magic',
        "        .word   1                ; app ABI version",
        f"        .word   {minabi}                ; minimum kernel ABI required",
        "        .word   0x0020           ; entry offset: the trampoline below",
        "        .byte   0                ; type: 0 = native 65816",
        f"        .byte   {banks}                ; banks occupied",
    ]
    body = ", ".join(str(ord(c)) for c in padded)
    lines += [
        f"        .byte   {body}  ; name[16]",
        "        .byte   0                ; SRAM quota, 8 KB blocks",
        "        .byte   0                ; flags",
        f"        .byte   {arena_page}               ; arena start page ($7Fpp00)",
        f"        .byte   {arena_pages}               ; arena pages (0 = 256)",
        "",
        ";;; Offset $20: the entry trampoline.",
        ";;; The header above is exactly 32 bytes, so this lands at a known",
        ";;; constant offset and the entry field never has to name a symbol.",
        ";;; A `.word app_start` cannot work here — app_start is a 24-bit",
        ";;; address in bank $@BANK@ and will not fit in a 16-bit relocation.",
        "        jmp     long:app_start",
    ]

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    open(out_path, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
